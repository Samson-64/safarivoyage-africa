import { SupportedLanguage, SupportedCurrency } from '../types';

export const CURRENCY_RATES: Record<SupportedCurrency, { symbol: string; rateFromUSD: number; name: string; position: 'prefix' | 'suffix' }> = {
  USD: { symbol: '$', rateFromUSD: 1, name: 'US Dollar', position: 'prefix' },
  EUR: { symbol: '€', rateFromUSD: 0.92, name: 'Euro', position: 'prefix' },
  GBP: { symbol: '£', rateFromUSD: 0.79, name: 'British Pound', position: 'prefix' },
  KES: { symbol: 'KSh ', rateFromUSD: 130.5, name: 'Kenyan Shilling', position: 'prefix' },
  ZAR: { symbol: 'R ', rateFromUSD: 18.2, name: 'South African Rand', position: 'prefix' },
  EGP: { symbol: 'E£ ', rateFromUSD: 48.5, name: 'Egyptian Pound', position: 'prefix' }
};

export function formatPrice(priceInUSD: number, currency: SupportedCurrency = 'USD'): string {
  const info = CURRENCY_RATES[currency] || CURRENCY_RATES.USD;
  const converted = Math.round(priceInUSD * info.rateFromUSD);
  if (info.position === 'suffix') {
    return `${converted.toLocaleString()} ${info.symbol}`;
  }
  return `${info.symbol}${converted.toLocaleString()}`;
}

export function convertCurrency(priceInUSD: number, currency: SupportedCurrency): number {
  const info = CURRENCY_RATES[currency] || CURRENCY_RATES.USD;
  return Math.round(priceInUSD * info.rateFromUSD);
}

